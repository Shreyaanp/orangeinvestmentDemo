"""Write a README.md into every scenario folder (the ticket, what the data holds, the answer key
and the trap) and an index of all cases at scenarios/README.md, so a human can understand the
test set without reading JSON.

Agents never see these files: they load data.json only and have no file tools. Rerun after
regenerating scenarios: python -m eval.describe
"""

from datetime import timedelta
from pathlib import Path

from incident.models import Dataset
from incident.sim.truth import Selector, Truth

ROOT = Path(__file__).resolve().parents[2]
FOLDERS = (ROOT / "scenarios", ROOT / "scenarios" / "rcaeval")


def _world(sid: str, data: Dataset) -> str:
    if sid.startswith("rca_"):
        return "RCAEval (real recorded telemetry, public benchmark)"
    if data.conversations:
        return "v2 app world (message-level simulation of a WhatsApp banking stack)"
    return "v1 synthetic (service-level simulation)"


def _selector(s: Selector) -> str:
    what = {
        "log": f"{s.level or 'any'} logs containing `{s.contains}`",
        "change": f"the change whose ref contains `{s.contains}`",
        "metric": f"metric `{s.metric}`" + (f" at or above {s.min_value}" if s.min_value else ""),
        "conversation": f"conversations containing `{s.contains}`"
        + (" with a failed tool call" if s.failed_tool else ""),
        "code": f"the commit touching `{s.contains}`",
    }[s.kind]
    return f"{s.service}: {what}, {s.start:%H:%M}–{s.end:%H:%M} UTC"


def _run(sid: str, rca: bool) -> list[str]:
    root = " --root scenarios/rcaeval" if rca else ""
    tape = (ROOT / "tapes" / sid).exists()
    lines = ["## Run it", "", "```powershell"]
    if tape:
        lines += [
            "# offline, no tokens: replays the recorded run",
            f'$env:LLM_BACKEND="replay"; python -m eval.run{root} --scenarios {sid} --no-judge',
        ]
    lines += [
        "# live (uses your Claude Code login)",
        f'$env:LLM_BACKEND="claude_code"; python -m eval.run{root} --scenarios {sid} --no-judge',
        "```",
    ]
    return lines


def describe(folder: Path) -> str:
    data = Dataset.model_validate_json((folder / "data.json").read_text("utf-8"))
    truth = Truth.model_validate_json((folder / "truth.json").read_text("utf-8"))
    sid, end = folder.name, data.start + timedelta(minutes=data.minutes)
    out = [
        f"# {sid}",
        "",
        f"World: {_world(sid, data)}. Expected outcome: **{truth.expected_status}**.",
        "",
        "## The ticket (all the agents are told)",
        "",
        f"> {data.incident.text}",
        "",
        f"Reported {data.incident.reported_at:%Y-%m-%d %H:%M} UTC.",
        "",
        "## What the data holds (`data.json`)",
        "",
        f"- Window: {data.start:%Y-%m-%d %H:%M} to {end:%H:%M} UTC ({data.minutes} min)",
        f"- Services ({len(data.topology.services)}): {', '.join(data.topology.services)}",
        f"- {len(data.logs):,} log lines, "
        f"{sum(len(v) for v in data.metrics.values())} metric series, "
        f"{len(data.changes)} changes, {len(data.history)} past incidents",
    ]
    if data.conversations:
        out.append(
            f"- {len(data.conversations):,} WhatsApp conversations traced end to end, "
            f"{len(data.code_changes)} git commits with diffs"
        )
    if data.tool_faults:
        out.append(f"- {len(data.tool_faults)} injected tool failures (the tools themselves flake)")
    if data.changes:
        out += ["", "| time (UTC) | kind | service | ref | note |", "|---|---|---|---|---|"]
        out += [
            f"| {c.ts:%H:%M} | {c.kind} | {c.service} | {c.ref} | {c.note} |" for c in data.changes
        ]
    out += [
        "",
        "## Answer key (spoiler, from `truth.json`; only `tests/eval/` reads it)",
        "",
    ]
    if not truth.faults:
        out.append("No root cause can be established from this data.")
    for f in truth.faults:
        out += [
            f"**{f.id} ({f.role})**: `{f.component}` / `{f.cause_type}`, "
            f"onset {f.onset:%H:%M} UTC.",
            "",
            f.description,
            "",
            "Decisive evidence a correct report should cite:",
            "",
            *[f"- {_selector(s)}" for s in f.decisive],
            "",
        ]
    out += ["## The trap", "", truth.trap, "", *_run(sid, sid.startswith("rca_"))]
    return "\n".join(out) + "\n"


INDEX_HEAD = """# Test cases

Every incident the system is evaluated on: {n} cases. Each folder has a README with the full
ticket, what the data holds, the answer key and the trap. The agents only ever read `data.json`;
`truth.json` (the answer key) is read only by `tests/eval/`. Generated by `python -m eval.describe`.

## Commands

```bash
python -m eval.demo <id>                  # replay a recorded live run ("yes" below), no key
python -m eval.demo <id> --live           # a real run of any case (Claude Code login)
python -m eval.run --scenarios <id> --systems multi baseline   # score both systems live
python -m eval.run --root scenarios/rcaeval --scenarios <id>   # the same, for an RCAEval case
python -m eval.validate                   # check every generated case is solvable with the tools
```

| id | world | ticket (what the agents are told) | expected | trap | recorded run |
|---|---|---|---|---|---|
"""


def _row(folder: Path) -> str:
    data = Dataset.model_validate_json((folder / "data.json").read_text("utf-8"))
    truth = Truth.model_validate_json((folder / "truth.json").read_text("utf-8"))
    sid = folder.name
    world = "RCAEval" if sid.startswith("rca_") else "app" if data.conversations else "service"
    tape = any((ROOT / "tapes" / sub / sid / "multi-1.jsonl").exists()
               for sub in ("", "v2demo", "hybrid", "exp_rca_default"))  # fmt: skip
    link = f"{folder.relative_to(FOLDERS[0]).as_posix()}/README.md"
    recorded = "yes" if tape else "-"
    return (f"| [{sid}]({link}) | {world} | {_cell(data.incident.text)} | "
            f"{truth.expected_status} | {_cell(truth.trap)} | {recorded} |")  # fmt: skip


def _cell(text: str) -> str:
    return " ".join(text.replace("|", "/").split())


def main() -> None:
    folders = [p for base in FOLDERS for p in sorted(base.iterdir()) if (p / "truth.json").exists()]
    for folder in folders:
        (folder / "README.md").write_text(describe(folder), "utf-8")
    rows = "\n".join(_row(f) for f in folders)
    index = INDEX_HEAD.format(n=len(folders)) + rows + "\n"
    (FOLDERS[0] / "README.md").write_text(index, "utf-8")


if __name__ == "__main__":
    main()
