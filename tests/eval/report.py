"""Assemble docs/RESULTS.md from saved score files, so every table traces back to a file.

Usage: python -m eval.report --out docs/RESULTS.md \\
         "Title|note|results/full1/rescored.jsonl" "Title|note|results/full2/scores.jsonl" ...
Each section is `title|note|path-to-jsonl` and gets a summary table and a per-scenario table.
"""

import argparse
from pathlib import Path

from eval.metrics import RunScore, scenario_table, summary_table

HEADER = """# Results

Generated by `python -m eval.report` from the score files named under each heading. Weighted score:
correct +1, partial +0.5, confidently wrong -1, abstained 0; on the one unanswerable scenario,
abstaining is +1 and answering is -1. Accuracy counts correct as 1 and partial as 0.5. "Decisive
evidence cited" is the share of the answer key's decisive evidence the report actually cites.
Runs are single samples per scenario and system unless stated: treat small differences as noise.
"""


def load(path: Path) -> list[RunScore]:
    lines = path.read_text("utf-8").splitlines()
    return [RunScore.model_validate_json(ln) for ln in lines if ln.strip()]


def section(spec: str) -> str:
    title, note, path = spec.split("|", 2)
    scores = load(Path(path))
    return (
        f"## {title}\n\n{note}\n\nSource: `{path}` ({len(scores)} runs)\n\n"
        f"{summary_table(scores)}\n\n{scenario_table(scores)}\n"
    )


def build(specs: list[str]) -> str:
    return HEADER + "\n" + "\n".join(section(s) for s in specs)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("sections", nargs="+")
    ap.add_argument("--out", type=Path, default=Path("docs/RESULTS.md"))
    a = ap.parse_args()
    a.out.write_text(build(a.sections), encoding="utf-8")
    print(f"wrote {a.out}")
